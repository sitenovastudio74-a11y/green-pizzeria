const fs = require("fs");

const dirPath = "C:\\Users\\OMPRAKASH KUMAR\\Projects\\green-pizzeria\\apps\\web\\app\\admin\\orders";
fs.mkdirSync(dirPath, { recursive: true });

const filePath = dirPath + "\\page.tsx";

const lines = [];
lines.push('"use client";');
lines.push('');
lines.push('import { useEffect, useState } from "react";');
lines.push('import { apiFetch } from "../../lib/api";');
lines.push('');
lines.push('const ALL_STATUSES = [');
lines.push('  "PENDING", "PAYMENT_PENDING", "PAYMENT_SUCCESS", "CONFIRMED", "PREPARING",');
lines.push('  "READY_FOR_PICKUP", "DELIVERY_BOOKING", "RIDER_ASSIGNED", "PICKED_UP",');
lines.push('  "OUT_FOR_DELIVERY", "DELIVERED", "PAYMENT_FAILED", "CANCELLED",');
lines.push('  "DELIVERY_FAILED", "REFUNDED",');
lines.push('];');
lines.push('');
lines.push('const STATUS_LABELS = {');
lines.push('  PENDING: "Waiting for payment",');
lines.push('  PAYMENT_PENDING: "Waiting for payment",');
lines.push('  PAYMENT_SUCCESS: "Payment confirmed",');
lines.push('  PAYMENT_FAILED: "Payment failed",');
lines.push('  CONFIRMED: "Order confirmed",');
lines.push('  PREPARING: "Being prepared",');
lines.push('  READY_FOR_PICKUP: "Ready",');
lines.push('  DELIVERY_BOOKING: "Finding a delivery partner",');
lines.push('  RIDER_ASSIGNED: "Rider assigned",');
lines.push('  PICKED_UP: "Picked up",');
lines.push('  OUT_FOR_DELIVERY: "Out for delivery",');
lines.push('  DELIVERED: "Delivered",');
lines.push('  CANCELLED: "Cancelled",');
lines.push('  DELIVERY_FAILED: "Delivery problem",');
lines.push('  REFUNDED: "Refunded",');
lines.push('};');
lines.push('');
lines.push('type OrderItem = { id: string; productName: string; quantity: number; subtotal: number };');
lines.push('type OrderComboItem = { id: string; comboName: string; quantity: number; subtotal: number };');
lines.push('type OrderUser = { id: string; name: string; phone: string | null; email: string | null };');
lines.push('type OrderAddress = { fullAddress: string; city: string; state: string; pincode: string };');
lines.push('type OrderPayment = { method: string; status: string };');
lines.push('');
lines.push('type Order = {');
lines.push('  id: string;');
lines.push('  orderNumber: string;');
lines.push('  orderType: "DINE_IN" | "TAKEAWAY" | "DELIVERY";');
lines.push('  status: string;');
lines.push('  total: number;');
lines.push('  createdAt: string;');
lines.push('  user: OrderUser;');
lines.push('  items: OrderItem[];');
lines.push('  comboItems?: OrderComboItem[];');
lines.push('  address: OrderAddress | null;');
lines.push('  payment: OrderPayment | null;');
lines.push('};');
lines.push('');
lines.push('async function readError(r: Response, fallback: string): Promise<string> {');
lines.push('  const data = await r.json().catch(() => null);');
lines.push('  if (Array.isArray(data?.message)) return data.message.join(", ");');
lines.push('  return data?.message || fallback;');
lines.push('}');
lines.push('');
lines.push('export default function AdminOrdersPage() {');
lines.push('  const [orders, setOrders] = useState<Order[]>([]);');
lines.push('  const [loading, setLoading] = useState(true);');
lines.push('  const [error, setError] = useState<string | null>(null);');
lines.push('  const [filter, setFilter] = useState<string>("ALL");');
lines.push('  const [expandedId, setExpandedId] = useState<string | null>(null);');
lines.push('  const [statusChoice, setStatusChoice] = useState<Record<string, string>>({});');
lines.push('  const [busyId, setBusyId] = useState<string | null>(null);');
lines.push('  const [rowError, setRowError] = useState<Record<string, string>>({});');
lines.push('');
lines.push('  const loadOrders = async () => {');
lines.push('    const r = await apiFetch("/orders");');
lines.push('    if (!r.ok) throw new Error(await readError(r, "Could not load orders."));');
lines.push('    const data: Order[] = await r.json();');
lines.push('    data.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());');
lines.push('    setOrders(data);');
lines.push('  };');
lines.push('');
lines.push('  useEffect(() => {');
lines.push('    loadOrders()');
lines.push('      .catch((err) => setError(err.message || "Could not load orders."))');
lines.push('      .finally(() => setLoading(false));');
lines.push('  }, []);');
lines.push('');
lines.push('  const toggleExpand = (order: Order) => {');
lines.push('    if (expandedId === order.id) {');
lines.push('      setExpandedId(null);');
lines.push('    } else {');
lines.push('      setExpandedId(order.id);');
lines.push('      setStatusChoice((prev) => ({ ...prev, [order.id]: prev[order.id] || order.status }));');
lines.push('    }');
lines.push('  };');
lines.push('');
lines.push('  const handleUpdateStatus = async (order: Order) => {');
lines.push('    const newStatus = statusChoice[order.id];');
lines.push('    if (!newStatus || newStatus === order.status) return;');
lines.push('    setBusyId(order.id);');
lines.push('    setRowError((prev) => ({ ...prev, [order.id]: "" }));');
lines.push('    try {');
lines.push('      const r = await apiFetch("/orders/" + order.id + "/status", {');
lines.push('        method: "PATCH",');
lines.push('        headers: { "Content-Type": "application/json" },');
lines.push('        body: JSON.stringify({ status: newStatus }),');
lines.push('      });');
lines.push('      if (!r.ok) throw new Error(await readError(r, "Could not update status."));');
lines.push('      await loadOrders();');
lines.push('    } catch (err: any) {');
lines.push('      setRowError((prev) => ({ ...prev, [order.id]: err.message || "Could not update status." }));');
lines.push('    } finally {');
lines.push('      setBusyId(null);');
lines.push('    }');
lines.push('  };');
lines.push('');
lines.push('  const handleCancel = async (order: Order) => {');
lines.push('    if (!window.confirm("Cancel order " + order.orderNumber + "?")) return;');
lines.push('    setBusyId(order.id);');
lines.push('    setRowError((prev) => ({ ...prev, [order.id]: "" }));');
lines.push('    try {');
lines.push('      const r = await apiFetch("/orders/" + order.id + "/cancel", { method: "PATCH" });');
lines.push('      if (!r.ok) throw new Error(await readError(r, "Could not cancel order."));');
lines.push('      await loadOrders();');
lines.push('    } catch (err: any) {');
lines.push('      setRowError((prev) => ({ ...prev, [order.id]: err.message || "Could not cancel order." }));');
lines.push('    } finally {');
lines.push('      setBusyId(null);');
lines.push('    }');
lines.push('  };');
lines.push('');
lines.push('  if (loading) {');
lines.push('    return <div className="p-8 text-center">Loading...</div>;');
lines.push('  }');
lines.push('');
lines.push('  const visibleOrders = filter === "ALL" ? orders : orders.filter((o) => o.status === filter);');
lines.push('');
lines.push('  return (');
lines.push('    <div className="max-w-3xl mx-auto px-4 py-10">');
lines.push('      <div className="flex items-center justify-between mb-6 gap-3 flex-wrap">');
lines.push('        <h1 className="text-2xl font-semibold">Orders</h1>');
lines.push('        <select');
lines.push('          value={filter}');
lines.push('          onChange={(e) => setFilter(e.target.value)}');
lines.push('          className="border rounded-lg px-3 py-2 text-sm"');
lines.push('        >');
lines.push('          <option value="ALL">All statuses</option>');
lines.push('          {ALL_STATUSES.map((s) => (');
lines.push('            <option key={s} value={s}>{(STATUS_LABELS as any)[s] || s}</option>');
lines.push('          ))}');
lines.push('        </select>');
lines.push('      </div>');
lines.push('');
lines.push('      {error && <p className="text-sm text-red-600 mb-4">{error}</p>}');
lines.push('');
lines.push('      {visibleOrders.length === 0 && (');
lines.push('        <p className="text-sm text-muted">No orders match this filter.</p>');
lines.push('      )}');
lines.push('');
lines.push('      {visibleOrders.map((order) => {');
lines.push('        const expanded = expandedId === order.id;');
lines.push('        return (');
lines.push('          <div key={order.id} className="border rounded-lg p-4 mb-3">');
lines.push('            <button onClick={() => toggleExpand(order)} className="w-full text-left">');
lines.push('              <div className="flex justify-between items-center gap-2 flex-wrap">');
lines.push('                <span className="font-medium">{order.orderNumber}</span>');
lines.push('                <span className="text-sm font-medium text-green-700">');
lines.push('                  {(STATUS_LABELS as any)[order.status] || order.status}');
lines.push('                </span>');
lines.push('              </div>');
lines.push('              <div className="flex justify-between gap-2 text-xs text-muted mt-1 flex-wrap">');
lines.push('                <span>{order.user?.name || "Unknown"} - {order.orderType}</span>');
lines.push('                <span>Rs. {order.total} - {new Date(order.createdAt).toLocaleString("en-IN")}</span>');
lines.push('              </div>');
lines.push('            </button>');
lines.push('');
lines.push('            {expanded && (');
lines.push('              <div className="mt-4 border-t pt-4">');
lines.push('                <div className="text-sm mb-3">');
lines.push('                  <p className="text-muted mb-1">Customer</p>');
lines.push('                  <p className="font-medium">{order.user?.name}</p>');
lines.push('                  <p className="text-xs text-muted">{order.user?.phone} {order.user?.email ? "- " + order.user.email : ""}</p>');
lines.push('                </div>');
lines.push('');
lines.push('                {order.address && (');
lines.push('                  <div className="text-sm mb-3">');
lines.push('                    <p className="text-muted mb-1">Delivery address</p>');
lines.push('                    <p>{order.address.fullAddress}, {order.address.city}, {order.address.state} {order.address.pincode}</p>');
lines.push('                  </div>');
lines.push('                )}');
lines.push('');
lines.push('                <div className="text-sm mb-3">');
lines.push('                  <p className="text-muted mb-1">Items</p>');
lines.push('                  {order.items.map((it) => (');
lines.push('                    <p key={it.id}>{it.productName} x{it.quantity} - Rs. {it.subtotal}</p>');
lines.push('                  ))}');
lines.push('                  {order.comboItems && order.comboItems.map((c) => (');
lines.push('                    <p key={c.id}>{c.comboName} x{c.quantity} - Rs. {c.subtotal}</p>');
lines.push('                  ))}');
lines.push('                </div>');
lines.push('');
lines.push('                {order.payment && (');
lines.push('                  <div className="text-sm mb-4">');
lines.push('                    <p className="text-muted mb-1">Payment</p>');
lines.push('                    <p>{order.payment.method} - {order.payment.status}</p>');
lines.push('                  </div>');
lines.push('                )}');
lines.push('');
lines.push('                <div className="flex gap-3 items-center flex-wrap">');
lines.push('                  <select');
lines.push('                    value={statusChoice[order.id] || order.status}');
lines.push('                    onChange={(e) => setStatusChoice((prev) => ({ ...prev, [order.id]: e.target.value }))}');
lines.push('                    className="border rounded-lg px-3 py-2 text-sm"');
lines.push('                  >');
lines.push('                    {ALL_STATUSES.map((s) => (');
lines.push('                      <option key={s} value={s}>{(STATUS_LABELS as any)[s] || s}</option>');
lines.push('                    ))}');
lines.push('                  </select>');
lines.push('                  <button');
lines.push('                    onClick={() => handleUpdateStatus(order)}');
lines.push('                    disabled={busyId === order.id}');
lines.push('                    className="bg-green-600 text-white rounded-lg px-4 py-2 text-sm font-medium"');
lines.push('                  >');
lines.push('                    Update status');
lines.push('                  </button>');
lines.push('                  <button');
lines.push('                    onClick={() => handleCancel(order)}');
lines.push('                    disabled={busyId === order.id}');
lines.push('                    className="text-red-600 text-sm font-medium"');
lines.push('                  >');
lines.push('                    Cancel order');
lines.push('                  </button>');
lines.push('                </div>');
lines.push('                {rowError[order.id] && (');
lines.push('                  <p className="text-sm text-red-600 mt-2">{rowError[order.id]}</p>');
lines.push('                )}');
lines.push('              </div>');
lines.push('            )}');
lines.push('          </div>');
lines.push('        );');
lines.push('      })}');
lines.push('    </div>');
lines.push('  );');
lines.push('}');

const content = lines.join("\n");

fs.writeFileSync(filePath, content, { encoding: "utf8" });
console.log("CREATED: " + filePath);
