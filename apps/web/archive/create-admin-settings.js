const fs = require("fs");

const dirPath = "C:\\Users\\OMPRAKASH KUMAR\\Projects\\green-pizzeria\\apps\\web\\app\\admin\\settings";
fs.mkdirSync(dirPath, { recursive: true });

const filePath = dirPath + "\\page.tsx";

const lines = [];
lines.push('"use client";');
lines.push('');
lines.push('import { useEffect, useState } from "react";');
lines.push('import { apiFetch } from "../../lib/api";');
lines.push('');
lines.push('type PickupAddress = {');
lines.push('  street: string;');
lines.push('  city: string;');
lines.push('  state: string;');
lines.push('  zip: string;');
lines.push('  phone: string;');
lines.push('};');
lines.push('');
lines.push('async function readError(r: Response, fallback: string): Promise<string> {');
lines.push('  const data = await r.json().catch(() => null);');
lines.push('  if (Array.isArray(data?.message)) return data.message.join(", ");');
lines.push('  return data?.message || fallback;');
lines.push('}');
lines.push('');
lines.push('export default function AdminSettingsPage() {');
lines.push('  const [loading, setLoading] = useState(true);');
lines.push('  const [error, setError] = useState<string | null>(null);');
lines.push('  const [saving, setSaving] = useState(false);');
lines.push('  const [saved, setSaved] = useState(false);');
lines.push('');
lines.push('  const [deliveryFee, setDeliveryFee] = useState("");');
lines.push('  const [taxRatePercent, setTaxRatePercent] = useState("");');
lines.push('  const [deliveryProvider, setDeliveryProvider] = useState("MANUAL");');
lines.push('  const [pickupAddress, setPickupAddress] = useState<PickupAddress>({');
lines.push('    street: "",');
lines.push('    city: "",');
lines.push('    state: "",');
lines.push('    zip: "",');
lines.push('    phone: "",');
lines.push('  });');
lines.push('');
lines.push('  useEffect(() => {');
lines.push('    apiFetch("/settings")');
lines.push('      .then(async (r) => {');
lines.push('        if (!r.ok) throw new Error(await readError(r, "Could not load settings."));');
lines.push('        return r.json();');
lines.push('      })');
lines.push('      .then((data: { key: string; value: string }[]) => {');
lines.push('        for (const setting of data) {');
lines.push('          if (setting.key === "delivery_fee") setDeliveryFee(setting.value);');
lines.push('          if (setting.key === "tax_rate_percent") setTaxRatePercent(setting.value);');
lines.push('          if (setting.key === "delivery_provider") setDeliveryProvider(setting.value);');
lines.push('          if (setting.key === "pickup_address") {');
lines.push('            try {');
lines.push('              const parsed = JSON.parse(setting.value);');
lines.push('              setPickupAddress({');
lines.push('                street: parsed.street || "",');
lines.push('                city: parsed.city || "",');
lines.push('                state: parsed.state || "",');
lines.push('                zip: parsed.zip || "",');
lines.push('                phone: parsed.phone || "",');
lines.push('              });');
lines.push('            } catch {}');
lines.push('          }');
lines.push('        }');
lines.push('      })');
lines.push('      .catch((err) => setError(err.message || "Could not load settings."))');
lines.push('      .finally(() => setLoading(false));');
lines.push('  }, []);');
lines.push('');
lines.push('  const putSetting = async (key: string, value: string) => {');
lines.push('    const r = await apiFetch("/settings/" + key, {');
lines.push('      method: "PUT",');
lines.push('      headers: { "Content-Type": "application/json" },');
lines.push('      body: JSON.stringify({ value }),');
lines.push('    });');
lines.push('    if (!r.ok) throw new Error(await readError(r, "Could not save " + key + "."));');
lines.push('  };');
lines.push('');
lines.push('  const handleSave = async () => {');
lines.push('    setError(null);');
lines.push('    setSaved(false);');
lines.push('');
lines.push('    const feeNum = Number(deliveryFee);');
lines.push('    if (!deliveryFee || isNaN(feeNum) || feeNum < 0) {');
lines.push('      setError("Enter a valid delivery fee.");');
lines.push('      return;');
lines.push('    }');
lines.push('    const taxNum = Number(taxRatePercent);');
lines.push('    if (!taxRatePercent || isNaN(taxNum) || taxNum < 0) {');
lines.push('      setError("Enter a valid tax rate percentage.");');
lines.push('      return;');
lines.push('    }');
lines.push('');
lines.push('    setSaving(true);');
lines.push('    try {');
lines.push('      await putSetting("delivery_fee", deliveryFee);');
lines.push('      await putSetting("tax_rate_percent", taxRatePercent);');
lines.push('      await putSetting("delivery_provider", deliveryProvider);');
lines.push('      await putSetting("pickup_address", JSON.stringify(pickupAddress));');
lines.push('      setSaved(true);');
lines.push('    } catch (err: any) {');
lines.push('      setError(err.message || "Could not save settings.");');
lines.push('    } finally {');
lines.push('      setSaving(false);');
lines.push('    }');
lines.push('  };');
lines.push('');
lines.push('  if (loading) {');
lines.push('    return <div className="p-8 text-center">Loading...</div>;');
lines.push('  }');
lines.push('');
lines.push('  return (');
lines.push('    <div className="max-w-lg mx-auto px-4 py-10">');
lines.push('      <h1 className="text-2xl font-semibold mb-8">Settings</h1>');
lines.push('');
lines.push('      {error && <p className="text-sm text-red-600 mb-4">{error}</p>}');
lines.push('      {saved && <p className="text-sm text-green-600 mb-4">Settings saved.</p>}');
lines.push('');
lines.push('      <div className="border rounded-lg p-4 mb-6">');
lines.push('        <h2 className="text-sm font-medium mb-3">Pricing</h2>');
lines.push('        <div className="flex gap-4">');
lines.push('          <div className="flex-1">');
lines.push('            <label className="block text-xs text-muted mb-1">Delivery fee (Rs.)</label>');
lines.push('            <input value={deliveryFee} onChange={(e) => setDeliveryFee(e.target.value)} className="w-full border rounded-lg px-3 py-2 text-sm" inputMode="numeric" />');
lines.push('          </div>');
lines.push('          <div className="flex-1">');
lines.push('            <label className="block text-xs text-muted mb-1">Tax rate (%)</label>');
lines.push('            <input value={taxRatePercent} onChange={(e) => setTaxRatePercent(e.target.value)} className="w-full border rounded-lg px-3 py-2 text-sm" inputMode="numeric" />');
lines.push('          </div>');
lines.push('        </div>');
lines.push('      </div>');
lines.push('');
lines.push('      <div className="border rounded-lg p-4 mb-6">');
lines.push('        <h2 className="text-sm font-medium mb-3">Delivery provider</h2>');
lines.push('        <select value={deliveryProvider} onChange={(e) => setDeliveryProvider(e.target.value)} className="w-full border rounded-lg px-3 py-2 text-sm">');
lines.push('          <option value="MANUAL">Manual</option>');
lines.push('          <option value="UBER_DIRECT">Uber Direct</option>');
lines.push('        </select>');
lines.push('      </div>');
lines.push('');
lines.push('      <div className="border rounded-lg p-4 mb-6">');
lines.push('        <h2 className="text-sm font-medium mb-3">Pickup address</h2>');
lines.push('        <label className="block text-xs text-muted mb-1">Street</label>');
lines.push('        <input value={pickupAddress.street} onChange={(e) => setPickupAddress({ ...pickupAddress, street: e.target.value })} className="w-full border rounded-lg px-3 py-2 text-sm mb-3" />');
lines.push('        <div className="flex gap-4 mb-3">');
lines.push('          <div className="flex-1">');
lines.push('            <label className="block text-xs text-muted mb-1">City</label>');
lines.push('            <input value={pickupAddress.city} onChange={(e) => setPickupAddress({ ...pickupAddress, city: e.target.value })} className="w-full border rounded-lg px-3 py-2 text-sm" />');
lines.push('          </div>');
lines.push('          <div className="flex-1">');
lines.push('            <label className="block text-xs text-muted mb-1">State</label>');
lines.push('            <input value={pickupAddress.state} onChange={(e) => setPickupAddress({ ...pickupAddress, state: e.target.value })} className="w-full border rounded-lg px-3 py-2 text-sm" />');
lines.push('          </div>');
lines.push('        </div>');
lines.push('        <div className="flex gap-4">');
lines.push('          <div className="flex-1">');
lines.push('            <label className="block text-xs text-muted mb-1">ZIP</label>');
lines.push('            <input value={pickupAddress.zip} onChange={(e) => setPickupAddress({ ...pickupAddress, zip: e.target.value })} className="w-full border rounded-lg px-3 py-2 text-sm" />');
lines.push('          </div>');
lines.push('          <div className="flex-1">');
lines.push('            <label className="block text-xs text-muted mb-1">Phone</label>');
lines.push('            <input value={pickupAddress.phone} onChange={(e) => setPickupAddress({ ...pickupAddress, phone: e.target.value })} className="w-full border rounded-lg px-3 py-2 text-sm" />');
lines.push('          </div>');
lines.push('        </div>');
lines.push('      </div>');
lines.push('');
lines.push('      <button onClick={handleSave} disabled={saving} className="w-full bg-green-600 text-white rounded-lg py-2.5 text-sm font-medium">');
lines.push('        {saving ? "Saving..." : "Save settings"}');
lines.push('      </button>');
lines.push('    </div>');
lines.push('  );');
lines.push('}');

const content = lines.join("\n");

fs.writeFileSync(filePath, content, { encoding: "utf8" });
console.log("CREATED: " + filePath);
